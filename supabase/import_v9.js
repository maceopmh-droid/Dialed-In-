#!/usr/bin/env node
// Import the V9 Sheet's history into the Supabase tables (phase 1).
//
//   node supabase/import_v9.js --html index.html --rows rows.json --out import.sql [--summary summary.json]
//
// rows.json: the Sheet as an array of rows (column G, index 6, holds each event's JSON), e.g. a CSV export
// turned into JSON. The app's own replay (app.process, run from the built index.html) decides what the history
// says, so the import reads it exactly the way the app does: latest event per id wins, deletes stay deleted.
//
// Choices:
//  * Every Sheet-era name becomes a profile with no sign-in (legacy_name = the name). Claiming links a sign-in.
//  * Migrated sessions are "Friends & groups", and their notes, photos and comments "Friends": old history
//    doesn't suddenly become public. People can open up their own sessions later.
//  * Today's group becomes a private group, "Original crew"; the goal switches carry over.
//  * Removed people who left nothing behind but a gear record (like the test user John) are skipped.
//  * Ids are derived from the Sheet's ids, so running the import twice gives the same rows.
const fs = require('fs');
const crypto = require('crypto');
const path = require('path');
const { loadApp } = require('./lib/app_in_node');

const arg = k => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : null; };
const HTML = arg('html') || path.join(__dirname, '..', 'index.html');
const ROWS = arg('rows'), OUT = arg('out'), SUMMARY = arg('summary');
if (!ROWS || !OUT) { console.error('usage: node supabase/import_v9.js --html index.html --rows rows.json --out import.sql [--summary summary.json]'); process.exit(2); }

// ---- the history, read by the app
const rows = JSON.parse(fs.readFileSync(ROWS, 'utf8'));
const events = rows.map(r => Array.isArray(r) ? r[6] : null).filter(x => typeof x === 'string' && x[0] === '{')
  .map(x => { try { return JSON.parse(x); } catch (e) { return null; } }).filter(Boolean);
const app = loadApp(HTML);
app.user = '';
app.process(events);
const beans = [...app.beans.values()], brews = [...app.brews.values()];

// ---- helpers
const uid = (...k) => { const h = crypto.createHash('md5').update(k.join('|')).digest('hex'); return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`; };
const q = v => (v === null || v === undefined) ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const qj = v => (v === null || v === undefined) ? 'null' : `${q(JSON.stringify(v))}::jsonb`;
const qa = a => `array[${(a || []).map(q).join(', ')}]::text[]`;
const num = v => { if (v === null || v === undefined || v === '') return 'null'; const n = Number(String(v).replace(',', '.')); return Number.isFinite(n) ? String(n) : 'null'; };
const ts = v => { const t = app.toTime(v); return t ? `${q(new Date(t).toISOString())}::timestamptz` : 'null'; };
const dateOnly = v => /^\d{4}-\d{2}-\d{2}$/.test(String(v || '').slice(0, 10)) && !isNaN(Date.parse(String(v).slice(0, 10))) ? q(String(v).slice(0, 10)) : 'null';
const clean = s => String(s || '').trim();

// ---- people: every name the history mentions
const { removed } = app.peopleState();
const gone = app.removedPeople ? app.removedPeople() : new Set();
const names = new Map();   // lower -> display name (first spelling seen)
const mention = n => { n = clean(n); if (!n || n.startsWith('__') || /^(unknown|undefined|null)$/i.test(n)) return; if (!names.has(n.toLowerCase())) names.set(n.toLowerCase(), n); };
app.knownPeople().forEach(mention);
beans.forEach(b => { mention(b.owner || b.user); (b.likes || []).forEach(mention); (b.comments || []).forEach(c => { mention(c.user); (c.likes || []).forEach(mention); }); (b.wantToTry || []).forEach(mention); });
brews.forEach(b => { mention(app.getBrewOwner(b)); (b.likes || []).forEach(mention); (b.comments || []).forEach(c => { mention(c.user); (c.likes || []).forEach(mention); }); });
[...app.customFlavors.values()].forEach(f => mention(f && f.user));
const skipped = [];
app.gearByUser.forEach((g, owner) => { if (gone.has(String(owner).toLowerCase()) && !names.has(String(owner).toLowerCase())) skipped.push(`${owner} (removed; only a gear record)`); else mention(owner); });

const profileId = n => uid('profile', clean(n).toLowerCase());
const used = new Set();
const handleFor = n => { let h = clean(n).toLowerCase().replace(/[^a-z0-9_]/g, ''); if (h.length < 2) h = (h + 'brewer').slice(0, 24); h = h.slice(0, 20); let x = h, i = 2; while (used.has(x)) x = h + i++; used.add(x); return x; };

const out = ['-- Dialed In: V9 Sheet import, generated by supabase/import_v9.js. Run as the database owner (bypasses row rules).', 'begin;'];
const add = s => out.push(s);
const count = {};
const tally = (k, n = 1) => { count[k] = (count[k] || 0) + n; };

for (const [lower, name] of names) {
  const color = app.normalizeHexColor(app.userColors[name] || '') || null;
  add(`insert into profiles (id, handle, display_name, color, legacy_name) values (${q(profileId(name))}, ${q(handleFor(name))}, ${q(name.slice(0, 40))}, ${q(color)}, ${q(name)});`);
  add(`insert into claim_codes (code, legacy_name) values (${q(crypto.randomBytes(6).toString('hex'))}, ${q(name)});`);
  tally('profiles');
}
const pid = n => { n = clean(n); return n && names.has(n.toLowerCase()) ? q(profileId(n)) : null; };

// ---- the original crew: today's group, private, with its goal switches
const crewMembers = app.knownPeople().filter(n => names.has(n.toLowerCase()));
if (crewMembers.length) {
  const owner = crewMembers.find(n => n.toLowerCase() === 'maceo') || crewMembers[0];
  const crew = uid('group', 'original-crew');
  const excluded = new Set(((app.groupSettings && app.groupSettings.goalExclude) || []).map(x => String(x).toLowerCase()));
  add(`insert into groups (id, name, is_open, owner_id, goal_on, awards_on) values (${q(crew)}, 'Original crew', false, ${pid(owner)}, true, true);`);
  crewMembers.forEach(n => { add(`insert into group_members (group_id, user_id, role, counts_in_goal) values (${q(crew)}, ${pid(n)}, ${q(n === owner ? 'owner' : 'member')}, ${!excluded.has(n.toLowerCase())});`); tally('group_members'); });
}

// ---- roasters and coffees
const roasterIds = new Map();
beans.forEach(b => { const r = clean(b.roaster); if (r && !roasterIds.has(r.toLowerCase())) { roasterIds.set(r.toLowerCase(), uid('roaster', r.toLowerCase())); add(`insert into roasters (id, name, created_by) values (${q(roasterIds.get(r.toLowerCase()))}, ${q(r)}, ${pid(b.owner || b.user)});`); tally('roasters'); } });
const coffeeId = id => uid('coffee', String(id));
const commentRows = (list, target, recordId) => {
  const ids = new Map((list || []).map(c => [String(c.id), uid('comment', recordId, String(c.id))]));
  (list || []).forEach(c => {
    const author = pid(c.user); if (!author) return;
    const parent = c.parentId && ids.has(String(c.parentId)) ? q(ids.get(String(c.parentId))) : 'null';
    add(`insert into comments (id, legacy_ref, ${target.col}, author_id, parent_id, body, audience, created_at) values (${q(ids.get(String(c.id)))}, ${q(recordId + '#' + c.id)}, ${q(target.id)}, ${author}, ${parent}, ${q(String(c.text || '').slice(0, 2000) || '…')}, 'friends', coalesce(${ts(c.timestamp)}, now()));`);
    tally('comments');
    [...new Set(c.likes || [])].forEach(n => { const who = pid(n); if (who) { add(`insert into comment_likes (comment_id, user_id) values (${q(ids.get(String(c.id)))}, ${who});`); tally('comment_likes'); } });
  });
};
beans.forEach(b => {
  const owner = pid(b.owner || b.user); if (!owner) { skipped.push(`coffee ${b.id} (no owner)`); return; }
  const id = coffeeId(b.id);
  add(`insert into coffees (id, legacy_id, owner_id, roaster_id, name, origin, process, variety, roast, roast_date, created_at, updated_at) values (${q(id)}, ${q(b.id)}, ${owner}, ${clean(b.roaster) ? q(roasterIds.get(clean(b.roaster).toLowerCase())) : 'null'}, ${q(clean(b.name) || 'Coffee')}, ${q(clean(b.origin) || null)}, ${q(clean(b.process) || null)}, ${q(clean(b.variety) || null)}, ${q(clean(b.roast) || null)}, ${dateOnly(b.roastDate)}, coalesce(${ts(b.date)}, now()), coalesce(${ts(b.eventAt || b.date)}, now()));`);
  tally('coffees');
  [...new Set(b.likes || [])].forEach(n => { const who = pid(n); if (who) { add(`insert into coffee_likes (coffee_id, user_id) values (${q(id)}, ${who});`); tally('coffee_likes'); } });
  commentRows(b.comments, { col: 'coffee_id', id }, b.id);
  [...new Set(b.wantToTry || [])].forEach(n => { const who = pid(n); if (who) { add(`insert into want_to_try (owner_id, coffee_key) values (${who}, ${q(app.beanGroupKey(b))}) on conflict do nothing;`); tally('want_to_try'); } });
});

// ---- sessions, their notes, photos, likes and comments
const MAPPED = new Set(['type', 'id', 'beanId', 'method', 'grind', 'dose', 'yield', 'time', 'acidity', 'sweetness', 'body', 'finish', 'balance', 'bitterness', 'complexity',
  'isMaster', 'masterProfile', 'notes', 'note', 'observations', 'observation', 'tastingNotes', 'user', 'owner', 'date', 'actor', 'actorColor', 'rating', 'likes', 'comments',
  'photo', 'equipment', 'equipmentSnapshot', 'eventAt', 'commentMeta', 'tasted', 'flavorNotes']);
brews.forEach(b => {
  const owner = pid(app.getBrewOwner(b)); if (!owner) { skipped.push(`session ${b.id} (no owner)`); return; }
  const id = uid('session', String(b.id));
  const taste = {}; ['acidity', 'sweetness', 'body', 'finish', 'bitterness', 'balance', 'complexity'].forEach(k => { if (b[k] !== undefined && b[k] !== '') taste[k] = b[k]; });
  const extras = {}; Object.keys(b).forEach(k => { if (!MAPPED.has(k) && b[k] !== undefined) extras[k] = b[k]; });
  const coffee = b.beanId && app.beans.has(String(b.beanId)) ? q(coffeeId(b.beanId)) : 'null';
  if (coffee === 'null' && b.beanId) { extras.beanId = String(b.beanId); tally('sessions_whose_coffee_was_deleted'); }   // keep the old link
  const grind = b.grind === null || b.grind === undefined || b.grind === '' ? null : String(b.grind);
  add(`insert into sessions (id, legacy_id, owner_id, coffee_id, audience, method, grind, dose, yield, time_s, rating, taste, tasted, flavor_notes, extras, equipment, master, brewed_at, created_at, updated_at) values (${q(id)}, ${q(b.id)}, ${owner}, ${coffee}, 'friends', ${q(clean(b.method) || null)}, ${q(grind)}, ${num(b.dose)}, ${num(b.yield)}, ${num(b.time)}, ${b.rating === undefined || b.rating === null || b.rating === '' ? 'null' : num(app.normalizeRating(b.rating))}, ${qj(taste)}, ${qa(b.tasted)}, ${qj(b.flavorNotes || null)}, ${qj(extras)}, ${qj({ ids: b.equipment || [], snapshot: b.equipmentSnapshot || [] })}, ${qj(b.isMaster || b.masterProfile ? { isMaster: Boolean(b.isMaster), profile: b.masterProfile || null } : null)}, coalesce(${ts(b.date)}, now()), coalesce(${ts(b.date)}, now()), coalesce(${ts(b.eventAt || b.date)}, now()));`);
  tally('sessions');
  const notes = app.getBrewNotes(b);
  if (notes) { add(`insert into session_notes (session_id, body, audience) values (${q(id)}, ${q(notes)}, 'friends');`); tally('session_notes'); }
  const photo = app.normalizePhoto(b.photo);
  if (photo) { add(`insert into session_photos (session_id, path, audience) values (${q(id)}, ${q(photo.fileId ? 'drive:' + photo.fileId : photo.url)}, 'friends');`); tally('session_photos'); }
  [...new Set(b.likes || [])].forEach(n => { const who = pid(n); if (who) { add(`insert into likes (session_id, user_id) values (${q(id)}, ${who});`); tally('likes'); } });
  commentRows(b.comments, { col: 'session_id', id }, b.id);
});

// ---- gear: equipment on the profile, the rest private
app.gearByUser.forEach((g, owner) => {
  const who = pid(owner); if (!who || skipped.some(s => s.startsWith(owner + ' '))) return;
  (g.items || []).forEach(it => { if (!it || !clean(it.name)) return; add(`insert into equipment (id, legacy_id, owner_id, type, name) values (${q(uid('equipment', owner, String(it.id || it.name)))}, ${q(it.id || null)}, ${who}, ${q(clean(it.type) || 'Other')}, ${q(clean(it.name))});`); tally('equipment'); });
  add(`insert into profile_gear (profile_id, recipes, last_by_method, roaster_prefs, favorites) values (${who}, ${qj(g.recipes || [])}, ${qj(g.lastByMethod || {})}, ${qj(g.roasters || {})}, ${qj({ fabFour: g.fabFour || [] })});`);
  tally('profile_gear');
});

// ---- custom tasting notes
[...app.customFlavors.values()].forEach(f => { const n = clean(f && f.name); if (!n) return; add(`insert into flavors (id, name, created_by) values (${q(uid('flavor', n.toLowerCase()))}, ${q(n)}, ${pid(f.user)}) on conflict (name) do nothing;`); tally('flavors'); });

// ---- the whole Sheet, kept as it was, so nothing from the old history is ever lost
rows.forEach((r, i) => { if (!Array.isArray(r) || typeof r[6] !== 'string' || r[6][0] !== '{') return; try { JSON.parse(r[6]); } catch (e) { return; }
  add(`insert into sheet_archive (row_no, logged_at, payload) values (${i + 1}, ${q(String(r[0] || ''))}, ${q(r[6])}::jsonb);`); tally('sheet_archive'); });

add('commit;');
fs.writeFileSync(OUT, out.join('\n') + '\n');
const summary = { events: events.length, counts: count, skipped, people: [...names.values()] };
if (SUMMARY) fs.writeFileSync(SUMMARY, JSON.stringify(summary, null, 2));
console.log(JSON.stringify({ events: events.length, ...count, skipped: skipped.length }));
